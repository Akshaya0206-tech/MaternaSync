import { useEffect, useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { updateFollowUp } from '../../api/doctorPortal';
import { fetchFollowUpsOverview } from '../../api/doctorOverview';
import type { FollowUp, FollowUpsOverview } from '../../api/doctorOverview';
import { StatusBadge } from '../../components/StatusBadge';
import { tx, useLanguage } from '../../i18n';
import { TASK_STATUS_TONE, friendlyTaskPriority, friendlyTaskStatus, formatFriendlyDate } from './format';

const STATUS_OPTIONS: FollowUp['status'][] = ['OPEN', 'IN_PROGRESS', 'WAITING', 'COMPLETED', 'CANCELLED'];
const OPEN: string[] = ['OPEN', 'IN_PROGRESS', 'WAITING'];

type Say = ReturnType<typeof useLanguage>['t'];

// The server writes the title of a patient's request about a visit in English: say it in the doctor's language.
const taskTitle = (t: Say, task: FollowUp) => {
  const change = task.sourceType === 'appointment_change' && /^Visit change requested: (move|cancel) the visit on (.+)$/.exec(task.title);
  if (!change) return task.title;
  return change[1] === 'move'
    ? t('Visit change requested: move the visit on {when}', { when: change[2] })
    : t('Visit change requested: cancel the visit on {when}', { when: change[2] });
};

/** When the task is due, in plain words: how many days late, due today, a date, or no date. Date arithmetic only. */
const dueLine = (t: Say, task: FollowUp) => {
  if (!task.dueDate) return t('No due date');
  if (task.daysOverdue) {
    const late = task.daysOverdue === 1 ? t('Overdue by 1 day') : t('Overdue by {count} days', { count: task.daysOverdue });
    return `${late} · ${t('Due {date}', { date: formatFriendlyDate(task.dueDate) })}`;
  }
  return task.isDue ? t('Due today') : t('Due {date}', { date: formatFriendlyDate(task.dueDate) });
};

export function FollowUpsPage() {
  const { t } = useLanguage();
  const navigate = useNavigate();
  const [data, setData] = useState<FollowUpsOverview | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  // A task that was just completed or cancelled leaves the lists; this says so and offers to put it back.
  const [closed, setClosed] = useState<{ id: string; title: string; status: string; previous: string } | null>(null);

  const load = () =>
    fetchFollowUpsOverview()
      .then((overview) => { setData(overview); setError(null); })
      .catch(() => setError(tx("We couldn't load your follow-ups. Please try again.")))
      .finally(() => setIsLoading(false));

  useEffect(() => { void load(); }, []);

  const changeStatus = async (task: FollowUp, status: string) => {
    const previous = task.status;
    setData((old) => old && { ...old, mine: old.mine.map((item) => (item.id === task.id ? { ...item, status: status as FollowUp['status'] } : item)) });
    setClosed(OPEN.includes(status) ? null : { id: task.id, title: taskTitle(t, task), status, previous });
    try {
      await updateFollowUp(task.id, { status });
    } catch {
      setClosed(null);
      void load();
    }
  };

  const undo = async () => {
    if (!closed) return;
    const { id, previous } = closed;
    setClosed(null);
    try {
      await updateFollowUp(id, { status: previous });
    } finally {
      void load();
    }
  };

  const mine = (data?.mine ?? []).filter((task) => OPEN.includes(task.status));
  const dueNow = mine.filter((task) => task.isDue);
  const later = mine.filter((task) => !task.isDue);
  const others = data?.others ?? [];

  const card = (task: FollowUp, mineToo: boolean) => (
    <li key={task.id} className="glass-panel followup-card">
      <div className="followup-main">
        <div className="followup-patient">{task.patientName}</div>
        <div className="followup-title">
          <span>{taskTitle(t, task)}</span>
          {task.autoGenerated && <span className="followup-auto">{t('Auto')}</span>}
        </div>
        {task.description && task.sourceType !== 'appointment_change' && <div className="followup-description">{task.description}</div>}
        <div className={`followup-due${task.daysOverdue ? ' followup-late' : ''}`}>{dueLine(t, task)}</div>
        <div className="followup-meta">
          {t('Priority: {priority}', { priority: friendlyTaskPriority(task.priority) })}
          {task.waitingFor && <> · {t('Waiting for: {who}', { who: task.waitingFor })}</>}
          {' · '}{task.ownerName ? t('Owner: {name}', { name: task.ownerName }) : t('No owner yet')}
        </div>
      </div>
      <div className="followup-actions">
        <StatusBadge label={friendlyTaskStatus(task.status)} tone={TASK_STATUS_TONE[task.status]} />
        {mineToo && task.sourceType === 'referral' && task.sourceId ? (
          <button onClick={() => navigate(`/doctor/referrals/${task.sourceId}`)} className="btn-outline-emerald">{t('Review Referral')}</button>
        ) : (
          mineToo && (
            <select
              value={task.status}
              aria-label={t('Status of the follow-up “{title}”', { title: taskTitle(t, task) })}
              onChange={(e) => void changeStatus(task, e.target.value)}
              className="followup-status"
            >
              {STATUS_OPTIONS.map((s) => <option key={s} value={s}>{friendlyTaskStatus(s)}</option>)}
            </select>
          )
        )}
        <Link className="btn-secondary" to={`/doctor/care-workspace?episodeId=${task.episodeId}&tab=operations`}>{t('Open in Connected Care')}</Link>
      </div>
    </li>
  );

  return (
    <main className="doctor-top" style={{ padding: '24px', flex: 1, maxWidth: '900px', margin: '0 auto', width: '100%' }}>
      <h1 className="page-title" style={{ fontSize: '1.4rem', margin: '0 0 6px 0' }}>{t('Follow-ups')}</h1>
      <p style={{ color: 'var(--text-secondary)', fontSize: '0.84rem', margin: '0 0 18px 0' }}>
        {t('Open tasks assigned to you, and the open tasks for your patients that someone else owns.')}
      </p>

      {isLoading && <div className="glass-panel" style={{ padding: '32px', textAlign: 'center', color: 'var(--text-muted)' }}>{t('Loading…')}</div>}
      {error && !isLoading && <div role="alert" className="glass-panel" style={{ padding: '24px', color: 'var(--rose-urgent)', textAlign: 'center' }}>{t(error)}</div>}

      {closed && (
        <div role="status" className="continuity-success followup-closed">
          {closed.status === 'COMPLETED' ? t('Marked as completed: {title}', { title: closed.title }) : t('Marked as cancelled: {title}', { title: closed.title })}{' '}
          <button type="button" className="btn-secondary" onClick={() => void undo()}>{t('Undo')}</button>
        </div>
      )}

      {data && !isLoading && !error && (
        <>
          <p className="followup-summary" role="status">
            {t('Assigned to you: {count}', { count: mine.length })} · {t('Due or overdue: {count}', { count: dueNow.length })}
            <span className="continuity-muted"> {t('The Dashboard card “Follow-ups owned by you” shows the first number.')}</span>
          </p>

          <section aria-labelledby="followups-due">
            <h2 id="followups-due" className="followup-heading">{t('Due or overdue')} ({dueNow.length})</h2>
            {dueNow.length === 0 ? (
              <div className="glass-panel followup-empty">{t('Nothing assigned to you is due or overdue.')}</div>
            ) : (
              <ul className="followup-list">{dueNow.map((task) => card(task, true))}</ul>
            )}
          </section>

          {later.length > 0 && (
            <section aria-labelledby="followups-later">
              <h2 id="followups-later" className="followup-heading">{t('Assigned to you, not due yet')} ({later.length})</h2>
              <ul className="followup-list">{later.map((task) => card(task, true))}</ul>
            </section>
          )}

          <section aria-labelledby="followups-others">
            <h2 id="followups-others" className="followup-heading">{t('Open tasks for your patients owned by someone else')} ({others.length})</h2>
            {others.length === 0 ? (
              <div className="glass-panel followup-empty">{t('Every open task for your patients is assigned to you.')}</div>
            ) : (
              <ul className="followup-list">{others.map((task) => card(task, false))}</ul>
            )}
          </section>
        </>
      )}
    </main>
  );
}
